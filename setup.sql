-- Fitway website enquiry table (Supabase SQL Editor)
-- This table is for the public enquiry form only.
create table if not exists public.fitway_enquiries (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  goal text,
  experience text,
  joining_time text,
  source text default 'Fitway website',
  created_at timestamptz not null default now()
);

alter table public.fitway_enquiries enable row level security;

-- Public visitors may submit enquiries, but cannot read or modify them.
drop policy if exists "Public can submit Fitway enquiries" on public.fitway_enquiries;
create policy "Public can submit Fitway enquiries"
on public.fitway_enquiries
for insert
to anon
with check (
  length(trim(name)) between 1 and 120
  and length(trim(phone)) between 7 and 40
);

